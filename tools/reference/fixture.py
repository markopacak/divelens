"""Writes the parity fixture for :core:analysis (synthetic images only, no personal media).

usage: python fixture.py [out]   (default: core/analysis/src/test/resources/parity.txt)

Each synthetic image is defined by an integer formula that the Kotlin test reproduces. For each one
the fixture lists the analysis-copy size, the statistics and the parameters computed with the
coefficients on the first line, so the Kotlin port can be checked against this reference.
"smooth" lines give corrected 8-bit pixels of the whole application step (smooth.py) with a small
working width, at sampled positions.
"""
import os, sys
import numpy as np
from common import ANALYSIS_WIDTH, box_downscale
from fit import params, stats, percentile_sorted
import smooth

HERE = os.path.dirname(os.path.abspath(__file__))
COEF = dict(c0=1.5409, c1=-2.1504, c2=0.4625, beta=0.4840, lo_pct=0.2277, red=-0.0422)
HI_PCT = 99.9
CAP = 3.0
BLACK_MAX = 0.45
STRENGTH = 0.78
SMOOTH_CASES = [("deep", 641, 479, 160), ("bright", 300, 200, 100), ("wide", 257, 131, 257), ("darkwater", 400, 300, 200)]

# name -> (r, g, b) as functions of integer x, y; the Kotlin test has the same table
VARIANTS = {
    "deep": lambda x, y: ((x * 7 + y * 3) % 40 + 5, 70 + (x * 5 + y * 11) % 120, 110 + (x * 3 + y * 13) % 140),
    "shallow": lambda x, y: (60 + (x * 7 + y * 3) % 140, 70 + (x * 5 + y * 11) % 150, 60 + (x * 3 + y * 13) % 120),
    "black": lambda x, y: ((x + y) % 2, (x + y) % 2, (x * y) % 2),
    "wide": lambda x, y: ((x * 7 + y * 3) % 256, (x * 5 + y * 11) % 256, 40 + (x * 3 + y * 13) % 200),
    "darkwater": lambda x, y: (25 + (x * 7 + y * 3) % 30, 40 + (x * 5 + y * 11) % 50 + y // 6, 90 + (x * 3 + y * 13) % 60 + y // 8),
    "bright": lambda x, y: ((x * 7 + y * 3) % 20 + 10, 120 + (x * 5 + y * 11) % 80, 180 + (x * 3 + y * 13) % 70),
}
SIZES = [(641, 479), (150, 100), (1000, 7)]


def image(name, w, h):
    y, x = np.mgrid[0:h, 0:w]
    r, g, b = VARIANTS[name](x, y)
    return np.stack([r, g, b], -1).astype(np.float32) / 255.0


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "core", "analysis", "src", "test", "resources", "parity.txt")
    th = [COEF[k] for k in ("c0", "c1", "c2", "beta", "lo_pct", "red")]
    lines = ["# generated by tools/reference/fixture.py; do not edit",
             "coefficients " + " ".join(f"{k}={v}" for k, v in COEF.items()) + f" hi_pct={HI_PCT} cap={CAP} black_max={BLACK_MAX}",
             "# name w h aw ah meanR meanG meanB lowG highG lowB highB a offset gainG gainB blackG blackB (identity: a=nan)"]
    for name in VARIANTS:
        for w, h in SIZES:
            small = box_downscale(image(name, w, h), ANALYSIS_WIDTH)
            st = stats(small)
            p = params(st, th, "prop", CAP, HI_PCT, BLACK_MAX, None, True, "black", True)
            lo = COEF["lo_pct"]
            vals = [*st["mean"], percentile_sorted(st["sorted_g"], lo), percentile_sorted(st["sorted_g"], HI_PCT),
                    percentile_sorted(st["sorted_b"], lo), percentile_sorted(st["sorted_b"], HI_PCT)]
            vals += [float("nan")] * 6 if p is None else [p["a"], p["offset"], p["gg"], p["gb"], p["lg"], p["lb"]]
            lines.append(f"{name} {w} {h} {small.shape[1]} {small.shape[0]} " + " ".join(f"{v:.9g}" for v in vals))
    lines.append(f"# smooth name w h workWidth strength x y R G B (8-bit result of smooth.py)")
    for name, w, h, ww in SMOOTH_CASES:
        img = image(name, w, h)
        p = params(stats(box_downscale(img, ANALYSIS_WIDTH)), th, "prop", CAP, HI_PCT, BLACK_MAX, None, True, "black", True)
        A, B = smooth.coefficients(box_downscale(img, min(ww, w)), p)
        res = np.round(smooth.apply(img, A, B, STRENGTH) * 255).astype(int)
        for k in range(40):
            x, y = (k * 97 + 3) % w, (k * 61 + 5) % h
            lines.append(f"smooth {name} {w} {h} {ww} {STRENGTH} {x} {y} " + " ".join(map(str, res[y, x])))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
